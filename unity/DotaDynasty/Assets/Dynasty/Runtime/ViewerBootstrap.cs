#nullable enable
using System;
using System.Globalization;
using System.IO;
using Dynasty.MatchSimulation.Rules;
using Dynasty.Presentation;
using UnityEngine;

namespace Dynasty.Unity
{
    /// <summary>
    /// Starts the draft room (then the match) when the scene loads, unless the player runs the determinism probe.
    /// Command line: <c>-dynasty-seed N</c>, <c>-dynasty-skip-draft</c>, <c>-dynasty-pack FILE</c> (a ruleset pack; without it the
    /// Dota pack in StreamingAssets when there is one, else the base rules); for automated checks
    /// <c>-dynasty-screenshots DIR [-dynasty-minute M]</c> (demo match) and <c>-dynasty-draft-screenshots DIR</c>.
    /// Without a seed an interactive run picks a random one (shown on screen, so a match can be replayed);
    /// the automated checks default to seed 1.
    /// </summary>
    public static class ViewerBootstrap
    {
        /// <summary>Seed of the draft and the match on screen.</summary>
        public static ulong Seed { get; private set; } = 1;

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
        private static void Start()
        {
            string[] args = Environment.GetCommandLineArgs();
            if (Value(args, DeterminismRunner.Argument) != null || UnityEngine.Object.FindAnyObjectByType<MatchViewer>() != null)
                return;

            string? draftShots = Value(args, "-dynasty-draft-screenshots");
            string? screenshots = Value(args, "-dynasty-screenshots");
            bool automated = draftShots != null || screenshots != null;
            ulong seed = ulong.TryParse(Value(args, "-dynasty-seed"), NumberStyles.Integer, CultureInfo.InvariantCulture, out ulong s) ? s
                : automated ? 1UL : (ulong)new System.Random().Next(1, 1000000);   // the viewer, not the simulation: the seed is its input
            Seed = seed;
            RulesetContent ruleset = RulesetSource.Load(PackPath(args));

            if (draftShots != null)
            {
                DraftScreen draft = DraftScreen.Create(seed, ruleset);
                draft.StartCoroutine(draft.CaptureAndQuit(draftShots));
                return;
            }

            if (screenshots == null && !Has(args, "-dynasty-skip-draft"))
            {
                DraftScreen.Create(seed, ruleset);   // the draft first; it starts the match
                return;
            }

            MatchViewer viewer = MatchViewer.Create(seed, ruleset);
            if (screenshots != null)
            {
                int minute = int.TryParse(Value(args, "-dynasty-minute"), NumberStyles.Integer, CultureInfo.InvariantCulture, out int m) ? m : 10;
                viewer.StartCoroutine(viewer.CaptureAndQuit(screenshots, minute));
            }
        }

        /// <summary>The Dota pack generated by tools/Dynasty.DotaPack and copied by tools/sync-unity.ps1.</summary>
        public const string DotaPackFile = "dota-7.41f.json";

        /// <summary>The pack to play: the one named on the command line, else the Dota pack in StreamingAssets if present, else none.</summary>
        private static string? PackPath(string[] args) => Value(args, "-dynasty-pack") ?? BundledPackPath();

        /// <summary>The Dota pack in StreamingAssets; null when it is not there.</summary>
        public static string? BundledPackPath()
        {
            string bundled = Path.Combine(Application.streamingAssetsPath, DotaPackFile);
            return File.Exists(bundled) ? bundled : null;
        }

        /// <summary>The bundled Dota pack's rules for the determinism checks; null without it.</summary>
        public static Dynasty.MatchSimulation.Rules.RulesetContent? BundledPack() =>
            BundledPackPath() is string path ? RulesetSource.Load(path) : null;

        private static bool Has(string[] args, string name) => System.Array.IndexOf(args, name) >= 0;

        private static string? Value(string[] args, string name)
        {
            for (int i = 0; i < args.Length - 1; i++)
            {
                if (args[i] == name)
                    return args[i + 1];
            }

            return null;
        }
    }
}
